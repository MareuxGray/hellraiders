#!/usr/bin/env python3
"""Generates the data half of src/shared/AssetRegistry (one data module per kind) from tools/assets_master.py,
and src/shared/Names.luau from data/names_first.txt and data/names_last.txt.

Run from the repo root after editing assets_master.py (then also run tools/build_assets.py from blueprint/):
    python -X utf8 tools/gen_shared.py
Never edit the generated files by hand; real asset ids go into tools/asset_ids.json (see Handoff.md).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from assets_master import ASSETS  # noqa: E402

KIND_ORDER = ["MDL", "ANIM", "SFX", "MUS", "VO", "UI", "VFX", "TEX"]
HEADER = "-- GENERATED by tools/gen_shared.py from tools/assets_master.py. Do not edit by hand.\n"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_real_ids():
    p = os.path.join(HERE, "asset_ids.json")
    if not os.path.exists(p):
        return {}
    return json.load(open(p, encoding="utf-8"))


def main():
    table = {}
    for a in ASSETS:  # last definition wins, same as build_assets.py
        table[a["id"]] = a
    real = load_real_ids()
    unknown = sorted(set(real) - set(table))
    if unknown:
        raise SystemExit(f"asset_ids.json has ids not in the master: {unknown}")
    out_dir = os.path.join(ROOT, "src", "shared", "AssetRegistry")
    os.makedirs(out_dir, exist_ok=True)
    total = 0
    for kind in KIND_ORDER:
        rows = sorted((a for a in table.values() if a["id"].split("-")[0] == kind), key=lambda a: a["id"])
        total += len(rows)
        lines = [HEADER, f"-- {kind}: {len(rows)} assets. id 0 = placeholder (25 §25.3).", "return {"]
        for a in rows:
            rid = int(real.get(a["id"], 0))
            size = ""
            if a["size"]:
                w, h, d = (float(x) for x in a["size"].lower().split("x"))
                size = f", size = {{ {w:g}, {h:g}, {d:g} }}"
            lines.append(
                f"\t[{lua_str(a['id'])}] = {{ kind = {lua_str(kind)}, id = {rid}, step = {lua_str(a['step'])}, "
                f"desc = {lua_str(a['desc'])}{size} }},"
            )
        lines.append("}")
        with open(os.path.join(out_dir, f"Data_{kind}.luau"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    print(f"AssetRegistry data: {total} assets in {len(KIND_ORDER)} files, {len(real)} real ids")

    # Names (13 §13.1): 120 first + 120 last
    def read_names(name):
        with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
            return [ln.strip() for ln in f if ln.strip()]

    first, last = read_names("names_first.txt"), read_names("names_last.txt")
    if len(first) != 120 or len(last) != 120:
        raise SystemExit(f"expected 120 + 120 names, got {len(first)} + {len(last)}")
    lines = [HEADER.replace("tools/assets_master.py", "data/names_first.txt and data/names_last.txt"),
             "-- Survivor names (13 §13.1): 120 first names and 120 last names.", "return {",
             "\tFirst = {"] + [f"\t\t{lua_str(n)}," for n in first] + ["\t},", "\tLast = {"] + \
            [f"\t\t{lua_str(n)}," for n in last] + ["\t},", "}"]
    with open(os.path.join(ROOT, "src", "shared", "Names.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Names: {len(first)} first, {len(last)} last")


if __name__ == "__main__":
    main()
